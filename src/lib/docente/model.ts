export type AuditIssue = {
  code:
    | "points_total"
    | "rubric_points"
    | "empty_prompt"
    | "no_guide"
    | "duplicate"
    | "mc_no_answer"
    | "mc_few_options"
    | "time_load"
    | "no_bibliography"
    | "no_questions";
  severity: "error" | "warning";
  questionIndex?: number;
  detail?: string;
};

/** Minutes a student plausibly needs per question type (rough heuristic, shown as an estimate). */
const MINUTES_BY_TYPE: Record<QuestionType, number> = {
  concept: 4,
  multiple_choice: 2,
  argument: 8,
  assumption: 7,
  error: 7,
  confrontation: 12,
  case: 15,
  evidence: 10,
  reconstruction: 10,
  essay: 25,
  map: 12,
};

export function estimateExamMinutes(exam: Pick<ExamContent, "questions">): number {
  return exam.questions.reduce((s, q) => s + (MINUTES_BY_TYPE[q.type] ?? 8), 0);
}

function normText(s: string) {
  return s.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, " ").trim();
}

/** Deterministic pre-export checks. Warnings, never an automatic "valid" stamp. */
export function auditExam(exam: ExamContent): AuditIssue[] {
  const issues: AuditIssue[] = [];
  if (exam.questions.length === 0) {
    issues.push({ code: "no_questions", severity: "error" });
    return issues;
  }
  const sum = examPointsSum(exam);
  if (sum !== exam.totalPoints) {
    issues.push({ code: "points_total", severity: "error", detail: `${sum}/${exam.totalPoints}` });
  }
  const seen = new Map<string, number>();
  exam.questions.forEach((q, i) => {
    if (!q.prompt.trim()) issues.push({ code: "empty_prompt", severity: "error", questionIndex: i });
    if (q.rubric.length > 0 && rubricPointsSum(q) !== q.points) {
      issues.push({
        code: "rubric_points",
        severity: "warning",
        questionIndex: i,
        detail: `${rubricPointsSum(q)}/${q.points}`,
      });
    }
    if (q.type === "multiple_choice") {
      if (q.options.filter((o) => o.trim()).length < 3)
        issues.push({ code: "mc_few_options", severity: "warning", questionIndex: i });
      if (q.correctOption === null || q.correctOption < 0 || q.correctOption >= q.options.length)
        issues.push({ code: "mc_no_answer", severity: "error", questionIndex: i });
    } else if (!q.answerGuide.trim() && q.rubric.length === 0) {
      issues.push({ code: "no_guide", severity: "warning", questionIndex: i });
    }
    const key = normText(q.prompt);
    if (key) {
      const prev = seen.get(key);
      if (prev !== undefined)
        issues.push({ code: "duplicate", severity: "warning", questionIndex: i, detail: String(prev + 1) });
      else seen.set(key, i);
    }
  });
  const est = estimateExamMinutes(exam);
  if (exam.durationMin > 0 && est > exam.durationMin * 1.15) {
    issues.push({ code: "time_load", severity: "warning", detail: `${est}/${exam.durationMin}` });
  }
  if (!exam.bibliography.trim()) issues.push({ code: "no_bibliography", severity: "warning" });
  return issues;
}

/** Deterministic pseudo-random generator so a B variant is reproducible from its seed. */
function mulberry32(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle<T>(arr: T[], rnd: () => number): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** Version B: same questions, different order and shuffled options (answer key kept in sync). */
export function makeVariantB(exam: ExamContent, seed = 7): ExamContent {
  const rnd = mulberry32(seed);
  const questions = shuffle(exam.questions, rnd).map((q) => {
    if (q.options.length < 2) return { ...q, id: uid("q") };
    const idx = shuffle(
      q.options.map((_, i) => i),
      rnd,
    );
    return {
      ...q,
      id: uid("q"),
      options: idx.map((i) => q.options[i]),
      correctOption: q.correctOption === null ? null : idx.indexOf(q.correctOption),
    };
  });
  return { ...exam, questions, variant: "B" };
}

/* ───────────── Maps ───────────── */

/** Radial layout: central node in the middle, its neighbours on a ring, the rest on an outer ring. */
export function layoutRadial(map: MapContent, width = 1200, height = 800): MapContent {
  if (map.nodes.length === 0) return map;
  const cx = width / 2;
  const cy = height / 2;
  const central = map.nodes.find((n) => n.kind === "central") ?? map.nodes[0];
  const neighbours = new Set<string>();
  for (const e of map.edges) {
    if (e.from === central.id) neighbours.add(e.to);
    if (e.to === central.id) neighbours.add(e.from);
  }
  const ring1 = map.nodes.filter((n) => n.id !== central.id && neighbours.has(n.id));
  const ring2 = map.nodes.filter((n) => n.id !== central.id && !neighbours.has(n.id));
  const pos = new Map<string, { x: number; y: number }>();
  pos.set(central.id, { x: cx, y: cy });
  const place = (nodes: MapNode[], rx: number, ry: number, offset: number) => {
    nodes.forEach((n, i) => {
      const a = offset + (i / Math.max(1, nodes.length)) * Math.PI * 2;
      pos.set(n.id, { x: Math.round(cx + rx * Math.cos(a)), y: Math.round(cy + ry * Math.sin(a)) });
    });
  };
  place(ring1, width * 0.28, height * 0.3, -Math.PI / 2);
  place(ring2, width * 0.44, height * 0.44, -Math.PI / 2 + 0.3);
  return { ...map, nodes: map.nodes.map((n) => ({ ...n, ...(pos.get(n.id) ?? { x: n.x, y: n.y }) })) };
}

/** Drops edges pointing at missing nodes, self-loops and exact duplicates. */
export function cleanEdges(map: MapContent): MapContent {
  const ids = new Set(map.nodes.map((n) => n.id));
  const seen = new Set<string>();
  const edges = map.edges.filter((e) => {
    if (!ids.has(e.from) || !ids.has(e.to) || e.from === e.to) return false;
    const k = `${e.from}|${e.to}|${e.relation}`;
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
  return { ...map, edges };
}

/** Logical reading of a relation: support, contradiction, questioning, or merely conceptual. */
export type EdgeLogic = "support" | "contradiction" | "question" | "conceptual";
export function edgeLogic(r: Relation): EdgeLogic {
  if (r === "grounds" || r === "infers" || r === "develops") return "support";
  if (r === "opposes") return "contradiction";
  if (r === "questions") return "question";
  return "conceptual";
}

/** Relations allowed in argument mode: proximity ("relates") is never a logical relation. */
export const ARGUMENT_RELATIONS: readonly Relation[] = ["grounds", "infers", "presupposes", "opposes", "questions"] as const;
export const ARGUMENT_NODE_KINDS: readonly NodeKind[] = ["premise", "inference", "conclusion", "central", "objection", "question", "case"] as const;

/** Which layer a node sits in when an argument is laid out top-down. */
function argumentLayer(k: NodeKind): number {
  if (k === "premise" || k === "case" || k === "concept" || k === "author" || k === "school" || k === "discipline") return 0;
  if (k === "inference") return 1;
  if (k === "central" || k === "conclusion") return 2;
  return 3; // objections and questions, under the conclusion
}

/** Top-down layout: premises, then inferences, then the conclusion, then objections and questions. */
export function layoutArgument(map: MapContent, width = 1200, height = 800): MapContent {
  const PER_ROW = 5;
  const layers: MapNode[][] = [[], [], [], []];
  for (const n of map.nodes) layers[argumentLayer(n.kind)].push(n);
  // Long layers wrap into several rows so nodes never overlap.
  const rows: MapNode[][] = [];
  for (const layer of layers) {
    for (let i = 0; i < layer.length; i += PER_ROW) rows.push(layer.slice(i, i + PER_ROW));
  }
  const pos = new Map<string, { x: number; y: number }>();
  rows.forEach((row, ri) => {
    const y = Math.round(((ri + 1) / (rows.length + 1)) * height);
    row.forEach((n, i) => {
      // Stagger alternate rows so vertical edges stay readable.
      const shift = ri % 2 && row.length < PER_ROW ? width / (PER_ROW + 1) / 2 : 0;
      pos.set(n.id, { x: Math.round(((i + 1) / (row.length + 1)) * width + shift * 0), y });
    });
  });
  return { ...map, nodes: map.nodes.map((n) => ({ ...n, ...(pos.get(n.id) ?? { x: n.x, y: n.y }) })) };
}

/** Nodes hidden on screen because a collapsed neighbour is their only connection. */
export function hiddenByCollapse(map: MapContent): Set<string> {
  const degree = new Map<string, number>();
  for (const e of map.edges) {
    degree.set(e.from, (degree.get(e.from) ?? 0) + 1);
    degree.set(e.to, (degree.get(e.to) ?? 0) + 1);
  }
  const collapsed = new Set(map.nodes.filter((n) => n.collapsed).map((n) => n.id));
  const hidden = new Set<string>();
  for (const e of map.edges) {
    for (const [hub, leaf] of [
      [e.from, e.to],
      [e.to, e.from],
    ]) {
      if (collapsed.has(hub) && !collapsed.has(leaf) && (degree.get(leaf) ?? 0) === 1) hidden.add(leaf);
    }
  }
  return hidden;
}

function fold(s: string) {
  return s.normalize("NFD").replace(/\p{Diacritic}/gu, "").toLowerCase();
}

/** Ids of nodes whose label or note contains the query (accent-insensitive). */
export function searchNodes(map: MapContent, query: string): Set<string> {
  const q = fold(query).trim();
  if (!q) return new Set();
  return new Set(map.nodes.filter((n) => fold(`${n.label} ${n.note}`).includes(q)).map((n) => n.id));
}

/** Merges an addition (new nodes/edges) into a map, dropping nodes whose label already exists. */
export function mergeMap(base: MapContent, add: { nodes: MapNode[]; edges: MapEdge[] }): MapContent {
  const labels = new Set(base.nodes.map((n) => fold(n.label)));
  const nodes = add.nodes.filter((n) => !labels.has(fold(n.label)));
  return cleanEdges({ ...base, nodes: [...base.nodes, ...nodes], edges: [...base.edges, ...add.edges] });
}

